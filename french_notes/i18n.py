def validate_language(language: object) -> str:
    """Use French when a saved language is missing, unsupported, or malformed."""
    if isinstance(language, str) and language in LANGUAGES:
        return language
    return DEFAULT_LANGUAGE


def translate(language: str, key: str, **params: object) -> str:
    """Return a translated label or format a summary; unknown keys raise KeyError."""
    return TRANSLATIONS[validate_language(language)][key].format(**params)
